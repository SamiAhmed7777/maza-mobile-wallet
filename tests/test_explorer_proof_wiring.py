class ParserContract(unittest.TestCase):

    def setUp(self):
        self.src = read(PARSER)

    def test_proof_payload_parsed_for_the_verifier(self):
        for token in ('o.getString("txid")', 'o.getString("merkleroot")',
                      'o.getJSONArray("merkle")', 'o.getInt("pos")'):
            self.assertIn(token, self.src)

    def test_structured_fields_carry_the_verify_targets(self):
        for token in ("public final Long txHeight;", "public final String txTxid;",
                      "public final int proofRowIndex;",
                      "public final List<HistoryEntry> history;"):
            self.assertIn(token, self.src)

    def test_history_rows_record_their_row_index_before_insert(self):
        self.assertIn("history.add(new HistoryEntry(txid, height, rows.size()));",
                      self.src)

    def test_proof_error_is_an_error_field_not_an_exception(self):
        proof_cls = self.src[self.src.index("public static final class Proof"):]
        self.assertIn("public final String error;", proof_cls)

    def test_tap_guard_is_encapsulated(self):
        entry_cls = self.src[
            self.src.index("public static final class HistoryEntry"):]
        self.assertIn("private boolean done;", entry_cls)
        self.assertIn("boolean markTapStarted()", entry_cls)
        self.assertNotIn("public boolean done;", entry_cls)


class ActivityWiring(unittest.TestCase):

    def setUp(self):
        self.src = read(ACTIVITY)
        self.code = strip_comments(self.src)

    def test_two_verify_flow_call_sites(self):
        # One in checkProof (tx view), one in verifyRow (history rows).
        self.assertEqual(self.code.count("MerkleVerify.verify("), 2,
                         "exactly the two verification flows may call verify")

    def test_two_proof_fetch_call_sites(self):
        self.assertEqual(self.code.count("client.proof("), 2)

    def test_history_rows_tap_to_verify(self):
        self.assertIn("setOnClickListener(v -> verifyRow(views, entry, baseText))",
                      self.code)

    def test_confirmed_tx_view_checks_automatically(self):
        body = self.code[self.code.index("private void render("):]
        self.assertIn("result.txHeight != null", body)
        self.assertIn("checkProof(views, height, txid, proofRow)", body)

    def test_verdicts_fail_closed_and_neutral(self):
        self.assertIn("proof.error == null", self.code)
        for token in ("R.string.explorer_proof_verified",
                      "R.string.explorer_proof_failed",
                      "R.string.explorer_proof_fetch_failed"):
            self.assertIn(token, self.code)
        self.assertNotIn("explorer_proof_not_checked", self.code)

    def test_updates_land_on_the_ui_thread_of_the_rendered_views(self):
        # fetch() + checkProof() + verifyRow() + the unconfirmed replacement
        # each return through the UI thread.
        self.assertEqual(self.code.count("runOnUiThread("), 4)
        # No field alias: the render-local views list is the only handle.
        self.assertNotIn("rowViews", self.code)
        self.assertIn("final List<TextView> views = new ArrayList<TextView>();",
                      self.code)

    def test_repeated_tap_cannot_refetch(self):
        self.assertIn("!entry.markTapStarted()", self.code)

    def test_unconfirmed_tx_gets_a_localized_no_proof_row(self):
        self.assertIn("R.string.explorer_proof_unconfirmed", self.code)
        # Only the transient "checking" placeholder stays parser-side (the
        # parser is android-free by design; every parse row is a literal).
        self.assertIn('"Proof: checking..."', read(PARSER))

    def test_no_activity_recreate(self):
        self.assertNotIn("recreate()", self.code)


class StringsAndDocs(unittest.TestCase):

    def test_strings_present_and_ascii(self):
        raw = open(STRINGS, "rb").read()
        raw.decode("ascii")
        strings = read(STRINGS)
        for token in ("explorer_proof_verified", "explorer_proof_failed",
                      "explorer_proof_fetch_failed",
                      "explorer_proof_unconfirmed"):
            self.assertIn(token, strings)
        self.assertIn(VERIFIED, strings)
        self.assertIn(FAILED, strings)
        self.assertIn(NOT_CHECKED, strings)

    def test_selftest_drives_the_port_with_documented_provenance(self):
        selftest = read(SELFTEST)
        self.assertIn("merkleVerifyChecks();", selftest)
        self.assertIn("MerkleVerify merkle proof check", selftest)
        self.assertIn("LIVE indexer proof", selftest)
        self.assertIn("maza_indexer/verify.py", selftest)

    def test_crosscheck_test_exists_and_uses_the_indexer_math(self):
        cross = read(CROSSCHECK)
        self.assertIn("from maza_indexer.proofs import merkle_branch_hex", cross)
        self.assertIn("from maza_indexer.verify import verify_merkle_proof", cross)
        self.assertIn("MerkleVerify.verify(", cross)

    def test_decisions_d17_states_the_trust_boundary(self):
        decisions = read(DECISIONS)
        self.assertIn("## D17", decisions)
        self.assertIn("Two-source verification mark", decisions)
        self.assertIn("does NOT independently verify block headers", decisions)
        self.assertIn("malicious indexer could", decisions)

    def test_user_guide_carries_the_explorer_mark(self):
        guide = read(USER_GUIDE)
        self.assertIn("CHAIN EXPLORER", guide)
        self.assertIn(VERIFIED, guide)
        self.assertIn("history rows verify when you tap them", guide)


if __name__ == "__main__":
    unittest.main()
