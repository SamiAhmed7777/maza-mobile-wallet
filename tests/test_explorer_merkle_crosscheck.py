#!/usr/bin/env python3
"""IDX-8 cross-implementation check: the Java MerkleVerify port vs the
indexer's own Python math.

MerkleVerify.java is the phone-side port of
maza_indexer/verify.py::verify_merkle_proof.  This test re-derives a full
vector set LIVE at test time with the indexer's own prover and verifier
(maza_indexer.proofs + hashutil + verify - imported, never reimplemented),
then compiles MerkleVerify.java + Hex.java + Base58Check.java standalone on
the desktop JVM with a generated driver and asserts the Java verdict on
every row equals the Python verdict AND the expected outcome:

  - every leaf position of 2-, 3-, and 4-leaf trees (true rows, covering
    left climbs, right climbs, and the odd-node duplication climb),
  - a single-tx block (empty branch, root == txid),
  - tampered sibling / wrong pos / wrong root (false rows),
  - the CLI-shaped width rule pos >= 2**len(branch) -> never true,
  - malformed inputs (short/non-hex sibling, short/non-hex txid) -> false.

The LIVE indexer vectors (block 41433/41430) are pinned in the desktop
SelfTest (crypto/SelfTest.merkleVerifyChecks) as baked constants with
provenance comments; this file stays fully offline by design.
"""
import hashlib
import os
import shutil
import subprocess
import sys
import tempfile
import unittest

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)

from maza_indexer.hashutil import double_sha256
from maza_indexer.proofs import merkle_branch_hex
from maza_indexer.verify import verify_merkle_proof

CRYPTO = os.path.join(REPO, "android", "src", "com", "mazawallet", "crypto")
MERKLE_VERIFY = os.path.join(CRYPTO, "MerkleVerify.java")
HEX = os.path.join(CRYPTO, "Hex.java")
BASE58 = os.path.join(CRYPTO, "Base58Check.java")
RIPEMD = os.path.join(CRYPTO, "Ripemd160.java")

JAVAC = shutil.which("javac")
JAVA = shutil.which("java")


def read_text(path):
    with open(path, "r", encoding="utf-8") as handle:
        return handle.read()


def leaf(i):
    return hashlib.sha256(b"maza-idx8-crosscheck-leaf-%d" % i).hexdigest()


def build_root(leaves_display):
    internals = [bytes.fromhex(t)[::-1] for t in leaves_display]
    level = list(internals)
    while len(level) > 1:
        if len(level) % 2:
            level.append(level[-1])
        level = [double_sha256(level[i] + level[i + 1])
                 for i in range(0, len(level), 2)]
    return level[0][::-1].hex()


def flip(hexstr):
    return ("0" if hexstr[0] != "0" else "1") + hexstr[1:]


def build_rows():
    """Every (name, txid, root, branch, pos, expected) row, derived live."""
    rows = []

    t0 = leaf(0)
    rows.append(("single-tx", t0, t0, [], 0, True))
    rows.append(("single-tx-wrong-root", t0, flip(t0), [], 0, False))
    rows.append(("single-tx-beyond-width", t0, t0, [], 1, False))

    for n in (2, 3, 4):
        leaves = [leaf(i) for i in range(n)]
        root = build_root(leaves)
        for idx in range(n):
            branch, pos = merkle_branch_hex(leaves, idx)
            rows.append(("%d-tx-pos-%d" % (n, idx), leaves[idx], root,
                         branch, idx, True))

    leaves4 = [leaf(i) for i in range(4)]
    root4 = build_root(leaves4)
    br1, _ = merkle_branch_hex(leaves4, 1)
    rows.append(("tampered-sibling", leaves4[1], root4,
                 [flip(br1[0])] + br1[1:], 1, False))
    rows.append(("wrong-pos", leaves4[1], root4, br1, 0, False))
    rows.append(("wrong-root", leaves4[1], flip(root4), br1, 1, False))
    rows.append(("beyond-width", leaves4[1], root4, br1, 4, False))
    rows.append(("short-sibling", leaves4[1], root4, [br1[0][:63]], 1, False))
    rows.append(("nonhex-sibling", leaves4[1], root4, ["zz" + br1[0][2:]], 1,
                 False))
    rows.append(("short-txid", leaves4[1][:63], root4, br1, 1, False))
    rows.append(("nonhex-txid", "gg" + leaves4[1][2:], root4, br1, 1, False))
    return rows


DRIVER_TEMPLATE = """package com.mazawallet;

import com.mazawallet.crypto.MerkleVerify;

/** Generated by test_explorer_merkle_crosscheck.py - rows regenerated live
 *  from the indexer's own math; do not edit by hand. */
public final class MerkleCrossProbe {{
    private static int checks = 0;
    private static int fails = 0;

    private static void row(String name, boolean got, boolean want) {{
        checks++;
        if (got == want) {{
            System.out.println("PASS " + name);
        }} else {{
            fails++;
            System.out.println("FAIL " + name + " got=" + got
                    + " want=" + want);
        }}
    }}

    public static void main(String[] args) {{
{rows}
        System.out.println(fails + " of " + checks
                + " MERKLE CROSSCHECK ROWS FAILED");
        if (fails > 0) System.exit(1);
        System.out.println("ALL MERKLE CROSSCHECK ROWS PASSED");
    }}
}}
"""


def java_row(name, txid, root, branch, pos, expected):
    branch_literal = ", ".join('"%s"' % b for b in branch)
    return (
        '        row("%s", MerkleVerify.verify("%s", "%s", '
        'new String[]{%s}, %d), %s);'
        % (name, txid, root, branch_literal, pos,
           "true" if expected else "false"))


class MerkleCrossCheck(unittest.TestCase):
    """The Java port agrees with the Python verify on every live-derived row."""

    def test_java_port_agrees_with_python_verify(self):
        if not JAVAC or not JAVA:
            self.skipTest("javac/java unavailable - JVM probe not run")
        rows = build_rows()
        # Python-side sanity: the indexer's own verifier answers `expected`
        # under the CLI-shaped width rule (pos >= 2**len is a usage error).
        for name, txid, root, branch, pos, expected in rows:
            provable = pos < (2 ** len(branch))
            got = verify_merkle_proof(txid, root, branch, pos) if provable \
                else False
            self.assertEqual(got, expected,
                             "python verify disagrees on %s" % name)

        driver_body = DRIVER_TEMPLATE.format(rows="\n".join(
            java_row(*row) for row in rows))
        workdir = tempfile.mkdtemp(prefix="maza-merkle-probe-")
        try:
            classes = os.path.join(workdir, "classes")
            os.makedirs(classes)
            sources = {
                "MerkleVerify.java": read_text(MERKLE_VERIFY),
                "Hex.java": read_text(HEX),
                "Base58Check.java": read_text(BASE58),
                "Ripemd160.java": read_text(RIPEMD),
                "MerkleCrossProbe.java": driver_body,
            }
            for name, body in sources.items():
                with open(os.path.join(workdir, name), "w",
                          encoding="ascii") as handle:
                    handle.write(body)
            compiled = subprocess.run(
                [JAVAC, "-nowarn", "-d", classes]
                + [os.path.join(workdir, name) for name in sources],
                stdout=subprocess.PIPE, stderr=subprocess.STDOUT, timeout=180)
            self.assertEqual(compiled.returncode, 0,
                             "javac failed:\n%s"
                             % compiled.stdout.decode("utf-8", "replace"))
            run = subprocess.run(
                [JAVA, "-classpath", classes, "com.mazawallet.MerkleCrossProbe"],
                stdout=subprocess.PIPE, stderr=subprocess.STDOUT, timeout=120)
            output = run.stdout.decode("utf-8", "replace")
            self.assertEqual(run.returncode, 0,
                             "merkle crosscheck failed:\n%s" % output)
            self.assertIn("ALL MERKLE CROSSCHECK ROWS PASSED", output)
            self.assertNotIn("FAIL ", output)
        finally:
            shutil.rmtree(workdir, ignore_errors=True)

    def test_row_set_covers_the_contract(self):
        rows = build_rows()
        names = [r[0] for r in rows]
        self.assertGreaterEqual(len(rows), 20)
        for climb in ("2-tx-pos-0", "2-tx-pos-1", "3-tx-pos-2", "4-tx-pos-3"):
            self.assertIn(climb, names)
        for negative in ("tampered-sibling", "wrong-pos", "wrong-root",
                         "beyond-width", "short-sibling", "nonhex-sibling",
                         "short-txid", "nonhex-txid", "single-tx-beyond-width"):
            self.assertIn(negative, names)


if __name__ == "__main__":
    unittest.main()
